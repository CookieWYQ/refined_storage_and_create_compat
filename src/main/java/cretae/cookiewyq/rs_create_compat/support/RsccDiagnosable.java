package cretae.cookiewyq.rs_create_compat.support;

import java.util.Map;

/**
 * <b>「这台机器现在是什么状态」的统一出口</b>（只读；供 {@code /rs_create_compat diag} 导出快照）。
 *
 * <h2>为什么需要它（用户 2026-10-05 直接要求）</h2>
 * <p>用户原话：<i>「我希望你能加强这个导出快照的功能，呃比如说能够导出当前网络所有这些机子里面的内部数据，
 * 就比如说导出某台机子我对它的设置什么的，以防我每一次都要跟你讲一下，或者说有时候我记错了，
 * 然后我讲错你也就修错的问题」</i>。</p>
 *
 * <p>这条要求在本轮被<b>实机验证过一次</b>：用户报「机器满了，但机械手和置物台完全是空的」，
 * 而当时的快照只能给出 {@code reason=EXECUTOR_OFFLINE} 一个词 —— 既看不出是「下游拒收」
 * 还是「某步没有机器认领」，也看不出那台机器的<b>总线勾了哪些类别、几个面是什么模式、
 * 升级槽装了什么、蓝图队列里有什么</b>。于是只能靠玩家复述，而复述与现场不一致时
 * 就会「讲错 ⇒ 修错」。</p>
 *
 * <h2>契约（实现方必须遵守）</h2>
 * <ul>
 *     <li><b>只读</b>：绝不搬运 / 生成 / 销毁任何资源，绝不改变任务状态、策略档位或方块数据；
 *     因此可以在任何时刻安全调用（含产线运行中）。</li>
 *     <li><b>绝不抛</b>：任何字段取不到就写 {@code "-"}；实现方自己 try-catch 可选，
 *     但 {@link RsccDiag} 侧也会整体兜底。</li>
 *     <li><b>确定性</b>：同一状态两次导出，除时间戳外逐字节一致（用 {@code TreeMap} / 排序列表）。</li>
 *     <li><b>可解释的字段名</b>：快照是给「下一位接手 + 玩家本人」看的，字段名要能自解释，
 *     不要用缩写（{@code faceConfig} 而不是 {@code fc}）。</li>
 * </ul>
 */
public interface RsccDiagnosable {

    /**
     * 本方块实体的完整状态快照（键值对；值必须是 JSON 可序列化的基本类型 / 列表 / map）。
     *
     * <p>约定必填字段（取不到写 {@code "-"}）：{@code pos}（{@code x,y,z}）、
     * {@code kind}（机器种类标识，如 {@code schematic_loader}）。</p>
     */
    Map<String, Object> rscc$diagReport();
}
